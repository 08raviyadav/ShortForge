#pragma once
// Tiny embedded 5x7 bitmap font for zero-dependency text overlays.
// Header-only; pure logic, unit tested.
#include <cstdint>
#include <string>

namespace sf {

// 7 bytes per glyph, 5 LSBs of each byte form one row.
inline const uint8_t* font_glyph(char c) {
    // Map: space, 0-9, A-Z, then punctuation . , ! ? ' : - % + /
    static const uint8_t kBlank[7] = {0, 0, 0, 0, 0, 0, 0};
    static const uint8_t kFont[][7] = {
        {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},  // space
        {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E},  // 0
        {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E},  // 1
        {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F},  // 2
        {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E},  // 3
        {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02},  // 4
        {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E},  // 5
        {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E},  // 6
        {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08},  // 7
        {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E},  // 8
        {0x0E, 0x11, 0x11, 0x1F, 0x01, 0x02, 0x0C},  // 9
        {0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},  // A
        {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E},  // B
        {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E},  // C
        {0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E},  // D
        {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F},  // E
        {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10},  // F
        {0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F},  // G
        {0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11},  // H
        {0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E},  // I
        {0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C},  // J
        {0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11},  // K
        {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F},  // L
        {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11},  // M
        {0x11, 0x19, 0x19, 0x15, 0x13, 0x13, 0x11},  // N
        {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E},  // O
        {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10},  // P
        {0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D},  // Q
        {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11},  // R
        {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E},  // S
        {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04},  // T
        {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E},  // U
        {0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04},  // V
        {0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11},  // W
        {0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11},  // X
        {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04},  // Y
        {0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F},  // Z
        {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C},  // .
        {0x00, 0x00, 0x00, 0x00, 0x0C, 0x04, 0x08},  // ,
        {0x04, 0x04, 0x04, 0x04, 0x04, 0x00, 0x04},  // !
        {0x0E, 0x11, 0x01, 0x02, 0x04, 0x00, 0x04},  // ?
        {0x04, 0x04, 0x08, 0x00, 0x00, 0x00, 0x00},  // '
        {0x00, 0x0C, 0x0C, 0x00, 0x00, 0x0C, 0x0C},  // :
        {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00},  // -
        {0x19, 0x1A, 0x02, 0x04, 0x08, 0x0D, 0x13},  // %
        {0x00, 0x04, 0x04, 0x1F, 0x04, 0x04, 0x00},  // +
        {0x01, 0x01, 0x02, 0x04, 0x08, 0x10, 0x10},  // /
    };
    static const char kMap[] = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.,!?' :-/";
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    for (size_t k = 0; k < sizeof(kMap) - 1; ++k)
        if (kMap[k] == c) return kFont[k];
    return kBlank;
}

// Width in pixels of text at the given integer scale (>= 1).
inline int text_width(const std::string& s, int scale) {
    if (scale < 1) scale = 1;
    return static_cast<int>(s.size()) * 6 * scale - scale;
}

// Draw text centered horizontally at cx, top edge at y_top. Returns bottom y.
inline int draw_text(uint8_t* rgb, int W, int H, const std::string& text, int cx, int y_top,
                     int scale, uint8_t r, uint8_t g, uint8_t b) {
    if (scale < 1) scale = 1;
    const int tw = text_width(text, scale);
    int x0 = cx - tw / 2;
    for (size_t ci = 0; ci < text.size(); ++ci) {
        const uint8_t* gl = font_glyph(text[ci]);
        const int gx = x0 + static_cast<int>(ci) * 6 * scale;
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if (gl[row] & (1 << (4 - col))) {
                    for (int sy = 0; sy < scale; ++sy) {
                        const int yy = y_top + row * scale + sy;
                        if (yy < 0 || yy >= H) continue;
                        for (int sx = 0; sx < scale; ++sx) {
                            const int xx = gx + col * scale + sx;
                            if (xx < 0 || xx >= W) continue;
                            uint8_t* p = rgb + (yy * W + xx) * 3;
                            p[0] = r;
                            p[1] = g;
                            p[2] = b;
                        }
                    }
                }
            }
        }
    }
    return y_top + 7 * scale;
}

// Alpha-blended filled rectangle (alpha 0..255).
inline void draw_bar(uint8_t* rgb, int W, int H, int x0, int y0, int x1, int y1, uint8_t r,
                     uint8_t g, uint8_t b, uint8_t alpha) {
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > W) x1 = W;
    if (y1 > H) y1 = H;
    const int ia = 255 - alpha;
    for (int y = y0; y < y1; ++y) {
        for (int x = x0; x < x1; ++x) {
            uint8_t* p = rgb + (y * W + x) * 3;
            p[0] = static_cast<uint8_t>((p[0] * ia + r * alpha) / 255);
            p[1] = static_cast<uint8_t>((p[1] * ia + g * alpha) / 255);
            p[2] = static_cast<uint8_t>((p[2] * ia + b * alpha) / 255);
        }
    }
}

}  // namespace sf
